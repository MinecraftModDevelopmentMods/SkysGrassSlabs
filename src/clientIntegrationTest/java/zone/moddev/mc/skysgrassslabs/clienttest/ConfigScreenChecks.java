package zone.moddev.mc.skysgrassslabs.clienttest;

import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.ScaledResolution;
import net.minecraft.client.resources.I18n;
import net.minecraft.util.ScreenShotHelper;
import net.minecraftforge.common.MinecraftForge;
import net.minecraftforge.common.config.Configuration;
import net.minecraftforge.common.config.Property;
import net.minecraftforge.fml.client.FMLClientHandler;
import net.minecraftforge.fml.client.IModGuiFactory;
import net.minecraftforge.fml.client.config.GuiConfig;
import net.minecraftforge.fml.client.config.IConfigElement;
import net.minecraftforge.fml.client.event.ConfigChangedEvent;
import net.minecraftforge.fml.common.Loader;
import net.minecraftforge.fml.common.ModContainer;
import zone.moddev.mc.skysgrassslabs.SkysGrassSlabs;
import zone.moddev.mc.skysgrassslabs.config.SkysGrassSlabsConfig;

/** Checks the actual registered screen and saved settings inside the disposable client. */
final class ConfigScreenChecks {
    private ConfigScreenChecks() {
    }

    static void run(Minecraft minecraft, String phase) {
        ModContainer mod = Loader.instance().getIndexedModList().get(SkysGrassSlabs.MOD_ID);

        require(!mod.getMetadata().autogenerated && !mod.getMetadata().description.isEmpty(),
                "The Mods page has processed metadata");
        require(SkysGrassSlabs.VERSION.equals(mod.getVersion()), "The loaded candidate version is correct");

        IModGuiFactory factory = FMLClientHandler.instance().getGuiFactoryFor(mod);

        require(factory != null && factory.hasConfigGui(), "The registered Config button is enabled");

        GuiConfig screen = (GuiConfig) factory.createConfigGui(minecraft.currentScreen);
        ScaledResolution resolution = new ScaledResolution(minecraft);

        screen.setWorldAndResolution(minecraft, resolution.getScaledWidth(), resolution.getScaledHeight());
        require(screen.configElements.size() == 2 && screen.entryList.listEntries.size() == 2
                && screen.allRequireMcRestart, "Both settings have widgets and require a restart");

        for (IConfigElement element : screen.configElements) {
            String labelKey = element.getLanguageKey();
            String tooltipKey = labelKey + ".tooltip";

            require(!I18n.format(labelKey).equals(labelKey), "The setting has a translated label");
            require(!I18n.format(tooltipKey).equals(tooltipKey), "The setting has translated help");
            require(element.getComment() != null && !element.getComment().trim().isEmpty(),
                    "The setting has help text");
        }

        minecraft.getFramebuffer().bindFramebuffer(true);
        minecraft.entityRenderer.setupOverlayRendering();
        screen.drawScreen(0, 0, 0);
        ScreenShotHelper.saveScreenshot(minecraft.gameDir, "grass-slabs-config-" + phase + ".png",
                minecraft.displayWidth, minecraft.displayHeight, minecraft.getFramebuffer());
        screen.onGuiClosed();

        Configuration configuration = SkysGrassSlabsConfig.configuration();
        Property generation = configuration.getCategory("worldgen").get("generateGrassSlabs");
        boolean originalChoice = generation.getBoolean();
        boolean activeChoice = SkysGrassSlabsConfig.generateGrassSlabs();

        try {
            generation.set(!originalChoice);
            MinecraftForge.EVENT_BUS.post(new ConfigChangedEvent.OnConfigChangedEvent("unrelated", null, false, true));
            require(read(configuration).get("worldgen", "generateGrassSlabs", true).getBoolean() == originalChoice,
                    "Another mod's event does not save Grass Slabs settings");

            MinecraftForge.EVENT_BUS.post(new ConfigChangedEvent.OnConfigChangedEvent(SkysGrassSlabs.MOD_ID,
                    null, false, true));
            require(read(configuration).get("worldgen", "generateGrassSlabs", true).getBoolean() != originalChoice,
                    "The Config event saves the selected value");
            require(SkysGrassSlabsConfig.generateGrassSlabs() == activeChoice,
                    "Saving a setting does not change generation before restarting");
        } finally {
            generation.set(originalChoice);
            SkysGrassSlabsConfig.saveChanges();
        }

        System.out.println("GRASS_SLABS_CONFIG_SCREEN_PASS phase=" + phase + " widgets=2 restart_safe=true");
    }

    private static Configuration read(Configuration source) {
        Configuration saved = new Configuration(source.getConfigFile());

        saved.load();
        return saved;
    }

    private static void require(boolean condition, String message) {
        if (!condition) {
            throw new IllegalStateException(message);
        }
    }
}
